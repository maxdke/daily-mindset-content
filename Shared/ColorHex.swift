import SwiftUI
import UIKit

/// Kleine Hilfe, um eine SwiftUI-Color als "#RRGGBB"-Hex-String in UserDefaults
/// (App Group) zu speichern – Color selbst lässt sich dort nicht direkt ablegen.
/// Wird für die frei wählbare Textfarbe des Spruchtexts genutzt (siehe
/// QuoteStore.customTextColor), da eine feste Farbe nicht in jedem Widget-Design
/// gut lesbar ist.
extension Color {
    var hexString: String {
        let uiColor = UIColor(self)
        var r: CGFloat = 0, g: CGFloat = 0, b: CGFloat = 0, a: CGFloat = 0
        uiColor.getRed(&r, green: &g, blue: &b, alpha: &a)
        let ri = Int((r * 255).rounded())
        let gi = Int((g * 255).rounded())
        let bi = Int((b * 255).rounded())
        return String(format: "#%02X%02X%02X", ri, gi, bi)
    }

    init?(hexString: String) {
        var hex = hexString.trimmingCharacters(in: .whitespacesAndNewlines)
        if hex.hasPrefix("#") { hex.removeFirst() }
        guard hex.count == 6, let value = UInt32(hex, radix: 16) else { return nil }
        let r = Double((value >> 16) & 0xFF) / 255
        let g = Double((value >> 8) & 0xFF) / 255
        let b = Double(value & 0xFF) / 255
        self.init(red: r, green: g, blue: b)
    }
}
